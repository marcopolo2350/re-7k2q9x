# Regenerates sw.js VERSION from the content of every precached file.
# Run from the app folder after any change to a precached file:  powershell -ExecutionPolicy Bypass -File build_sw.ps1
# A new VERSION makes the browser install the new service worker, which then replaces the old shell cache.
$ErrorActionPreference = "Stop"
$swPath = Join-Path $PSScriptRoot "sw.js"
$sw = Get-Content -Raw -Encoding UTF8 $swPath
$m = [regex]::Match($sw, "const PRECACHE=\[(.*?)\];")
if (-not $m.Success) { throw "PRECACHE list not found in sw.js" }
$files = [regex]::Matches($m.Groups[1].Value, "'([^']+)'") | ForEach-Object { $_.Groups[1].Value -replace '\?.*$', '' }
$sha = [System.Security.Cryptography.SHA256]::Create()
$ms = New-Object System.IO.MemoryStream
foreach ($f in $files) {
  if ($f -eq "./") { continue }
  $p = Join-Path $PSScriptRoot $f
  if (-not (Test-Path $p)) { throw "precached file missing: $f" }
  $bytes = [System.IO.File]::ReadAllBytes($p)
  $ms.Write([System.Text.Encoding]::UTF8.GetBytes($f + "`n"), 0, ([System.Text.Encoding]::UTF8.GetBytes($f + "`n")).Length)
  $ms.Write($bytes, 0, $bytes.Length)
}
$hash = ([BitConverter]::ToString($sha.ComputeHash($ms.ToArray()))).Replace("-", "").ToLower().Substring(0, 10)
$new = [regex]::Replace($sw, 'const VERSION="[^"]*";', "const VERSION=`"$hash`";")
$new = $new -replace 'Generated by build_sw.py; do not edit by hand\.', 'Regenerate with build_sw.ps1 after changing any precached file.'
if ($new -ne $sw) { [System.IO.File]::WriteAllText($swPath, $new, (New-Object System.Text.UTF8Encoding($false))) }
Write-Output "VERSION=$hash"
